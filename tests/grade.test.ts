import { readFileSync, existsSync } from "node:fs";
import { describe, expect, it } from "vitest";
import { buildGradeLut, DI_GREY, diToLin, gradeKey, linToDI, NEUTRAL_GRADE, parseCube, sampleCube, slog3ToLin, toCube } from "../lib/grade";

const at = (lut: Float32Array, size: number, r: number, g: number, b: number) => {
  const k = (r + g * size + b * size * size) * 3;
  return [lut[k], lut[k + 1], lut[k + 2]];
};

describe("colour transforms", () => {
  it("S-Log3 middle grey (code 420) is 0.18 linear", () => {
    expect(slog3ToLin((420 - 64) / 876)).toBeCloseTo(0.18, 5);
    expect(slog3ToLin((95 - 64) / 876)).toBeCloseTo(0, 6);
  });
  it("DaVinci Intermediate round-trips, grey at 0.336", () => {
    expect(DI_GREY).toBeCloseTo(0.336, 3);
    for (const l of [0, 0.001, 0.18, 1, 10, 100]) expect(diToLin(linToDI(l))).toBeCloseTo(l, 6);
  });
  it("Rec.709 footage with no adjustment and no LUT comes back unchanged", () => {
    const n = 9;
    const lut = buildGradeLut({ ...NEUTRAL_GRADE, profile: "rec709" }, null, n);
    for (const [r, g, b] of [[0, 0, 0], [8, 8, 8], [4, 4, 4], [8, 2, 0], [1, 5, 7]]) {
      const v = at(lut, n, r, g, b);
      expect(v[0]).toBeCloseTo(r / 8, 3); expect(v[1]).toBeCloseTo(g / 8, 3); expect(v[2]).toBeCloseTo(b / 8, 3);
    }
  });
  it("exposure brightens, white balance warms, saturation 0 is grey", () => {
    const n = 17, mid = 8;
    const base = at(buildGradeLut({ ...NEUTRAL_GRADE, profile: "rec709" }, null, n), n, mid, mid, mid);
    const up = at(buildGradeLut({ ...NEUTRAL_GRADE, profile: "rec709", exposure: 1 }, null, n), n, mid, mid, mid);
    expect(up[1]).toBeGreaterThan(base[1]);
    const warm = at(buildGradeLut({ ...NEUTRAL_GRADE, profile: "rec709", temp: 50 }, null, n), n, mid, mid, mid);
    expect(warm[0]).toBeGreaterThan(warm[2]);
    const grey = at(buildGradeLut({ ...NEUTRAL_GRADE, profile: "rec709", sat: 0 }, null, n), n, 16, 4, 0);
    expect(Math.abs(grey[0] - grey[2])).toBeLessThan(0.02);
  });
  it("the look LUT gets the picture in DaVinci Intermediate", () => {
    // An identity look LUT: S-Log3 grey comes out as DI grey.
    const n = 5, data = new Float32Array(n * n * n * 3);
    for (let b = 0, k = 0; b < n; b++) for (let g = 0; g < n; g++) for (let r = 0; r < n; r++, k += 3) { data[k] = r / 4; data[k + 1] = g / 4; data[k + 2] = b / 4; }
    const look = { size: n, data, min: [0, 0, 0] as [number, number, number], max: [1, 1, 1] as [number, number, number] };
    const s = [0, 0, 0];
    sampleCube(look, 0.3, 0.6, 0.9, s);
    expect(s[0]).toBeCloseTo(0.3, 6); expect(s[2]).toBeCloseTo(0.9, 6);
    const size = 65;
    const lut = buildGradeLut(NEUTRAL_GRADE, look, size);
    // Code 420 ≈ index 0.4064 × 64 = 26 (grey on the 65 grid).
    const v = at(lut, size, 26, 26, 26);
    expect(v[1]).toBeCloseTo(linToDI(slog3ToLin(26 / 64)), 2);
  });
  it("cube files are read and written", () => {
    const lut = buildGradeLut(NEUTRAL_GRADE, null, 3);
    const back = parseCube(toCube(lut, 3));
    expect(back.size).toBe(3);
    expect(back.data[back.data.length - 1]).toBeCloseTo(lut[lut.length - 1], 5);
    expect(() => parseCube("LUT_3D_SIZE 2\n0 0 0\n")).toThrow();
    expect(gradeKey(undefined)).toBe("");
    expect(gradeKey({ ...NEUTRAL_GRADE, profile: "none" })).toBe("");
  });
  const real = "/Users/andyhaquin/Downloads/BLURBLUR_GRADE_FILMLOOK.cube";
  it.skipIf(!existsSync(real))("reads a LUT generated by DaVinci", () => {
    const l = parseCube(readFileSync(real, "utf8"));
    expect(l.size).toBe(65);
  });
});
