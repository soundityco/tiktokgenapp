describe("colour wheels and the outputs", async () => {
  const G = await import("../lib/grade");
  const N = 17;
  const at = (lut: Float32Array, r: number, g: number, b: number) => { const k = ((b * N + g) * N + r) * 3; return [lut[k], lut[k + 1], lut[k + 2]]; };
  const base = { ...G.NEUTRAL_GRADE, exposure: 0.4 };
  const plain = G.buildGradeLut(base, null, N);

  it("at zero the wheels change nothing (the grades made before stay as they were)", () => {
    const z = G.buildGradeLut({ ...base, wheels: { lift: { x: 0, y: 0, l: 0 }, gain: { x: 0, y: 0, l: 0 } } }, null, N);
    expect(Array.from(z)).toEqual(Array.from(plain));
    expect(G.wheelsOn({ ...base, wheels: { gamma: { x: 0, y: 0, l: 0 } } })).toBe(false);
  });
  it("shadows lift the blacks most, highlights the top most, a red puck makes it redder", () => {
    const lift = G.buildGradeLut({ ...base, wheels: { lift: { x: 0, y: 0, l: 1 } } }, null, N);
    const dark = 4, bright = 13;
    const up = (l: Float32Array, i: number) => at(l, i, i, i)[1] - at(plain, i, i, i)[1];
    expect(up(lift, dark)).toBeGreaterThan(up(lift, bright));
    const gain = G.buildGradeLut({ ...base, wheels: { gain: { x: 0, y: 0, l: -0.5 } } }, null, N);
    expect(at(gain, bright, bright, bright)[1]).toBeLessThan(at(plain, bright, bright, bright)[1]);
    const red = G.buildGradeLut({ ...base, wheels: { gamma: { x: 0, y: 0.8, l: 0 } } }, null, N);
    const [r0, g0] = at(plain, 9, 9, 9), [r1, g1] = at(red, 9, 9, 9);
    expect(r1 - g1).toBeGreaterThan(r0 - g0 + 0.02);
  });
  it("a camera LUT gets the camera's own log: one that makes the app's Rec.709 gives the same picture, the grade before it kept", () => {
    // A camera LUT (S-Log3 code / 1023 in) made of the app's own conversion, without grade.
    // (65 points, as fine camera LUTs: a coarser one made from another LUT would only measure its own interpolation.)
    const S = 65, ref = G.buildGradeLut(G.NEUTRAL_GRADE, null, S), data = new Float32Array(S * S * S * 3);
    const sampled = (v: number[]) => { const o = [0, 0, 0]; G.sampleCube({ size: S, data: ref, min: [0, 0, 0], max: [1, 1, 1] }, v[0], v[1], v[2], o); return o; };
    for (let b = 0, k = 0; b < S; b++) for (let g = 0; g < S; g++) for (let r = 0; r < S; r++, k += 3) {
      const v = [r, g, b].map((i) => ((i / (S - 1)) * 1023 - 64) / 876); // its input as the app's video levels
      data.set(sampled(v), k);
    }
    const cam = { size: S, data, min: [0, 0, 0] as [number, number, number], max: [1, 1, 1] as [number, number, number] };
    // A grade before it (exposure down: the picture stays within the codes this test LUT covers, 64 to 940).
    const graded = { ...G.NEUTRAL_GRADE, exposure: -0.4 }, plainGraded = G.buildGradeLut(graded, null, N);
    const viaCamera = G.buildGradeLut({ ...graded, lut: { id: "a", name: "Alister", kind: "camera" } }, cam, N);
    let worst = 0;
    // Greys and warm tones (skin…); very saturated cyans fall under this test LUT's floor (code 64, a real one goes to 0).
    for (let i = 3; i < N - 2; i++) for (const [r, g, b] of [[i, i, i], [i, i - 1, i - 2], [i, i - 1, i - 1]]) {
      const a = at(viaCamera, r, g, b), p = at(plainGraded, r, g, b);
      worst = Math.max(worst, ...a.map((x, c) => Math.abs(x - p[c])));
    }
    expect(worst).toBeLessThan(0.02);
  });
});

describe("parts turned off", async () => {
  const G = await import("../lib/grade");
  it("a part off changes nothing and keeps its settings; back on, all is as before", () => {
    const g = { ...G.NEUTRAL_GRADE, exposure: 1, sat: 1.3, wheels: { gain: { x: 0.2, y: 0, l: 0.5 } }, vignette: 40, grain: 20 };
    const all = Array.from(G.buildGradeLut(g, null, 9));
    const plain = Array.from(G.buildGradeLut(G.NEUTRAL_GRADE, null, 9));
    const off = { ...g, bypass: { corrections: true, wheels: true, finish: true } };
    expect(Array.from(G.buildGradeLut(off, null, 9))).toEqual(plain);
    expect(G.effectiveGrade(off)).toMatchObject({ exposure: 0, sat: 1, vignette: 0, grain: 0 });
    expect(off.exposure).toBe(1); // kept
    expect(Array.from(G.buildGradeLut({ ...g, bypass: {} }, null, 9))).toEqual(all);
    // only the wheels off: the corrections still act
    const noWheels = Array.from(G.buildGradeLut({ ...g, bypass: { wheels: true } }, null, 9));
    expect(noWheels).toEqual(Array.from(G.buildGradeLut({ ...g, wheels: undefined }, null, 9)));
    expect(G.gradeKey({ ...g, bypass: { wheels: true } })).not.toBe(G.gradeKey(g));
  });
});

describe("a LUT's input and output (as a CST before it)", async () => {
  const G = await import("../lib/grade");
  const N = 17;
  const identity = (S: number) => {
    const d = new Float32Array(S * S * S * 3);
    for (let b = 0, k = 0; b < S; b++) for (let g = 0; g < S; g++) for (let r = 0; r < S; r++, k += 3) d.set([r / (S - 1), g / (S - 1), b / (S - 1)], k);
    return { size: S, data: d, min: [0, 0, 0] as [number, number, number], max: [1, 1, 1] as [number, number, number] };
  };
  const id = identity(65);
  const base = { ...G.NEUTRAL_GRADE, exposure: -0.3, sat: 1.1 };
  const plain = G.buildGradeLut(base, null, N);
  // Over the colours the picture can show (none of its channels clipped by the app's own conversion): far out of gamut,
  // a value under zero is clamped by any LUT's domain, an identity one too.
  const worst = (a: Float32Array) => {
    let w = 0;
    for (let i = 0; i < a.length; i += 3) {
      if ([0, 1, 2].some((c) => plain[i + c] < 0.02 || plain[i + c] > 0.98)) continue;
      for (let c = 0; c < 3; c++) w = Math.max(w, Math.abs(a[i + c] - plain[i + c]));
    }
    return w;
  };
  const lut = (input: "camera" | "dwg" | "cineon709" | "gamma709", extra = {}) => ({ id: "x", name: "x", input, output: "same" as const, ...extra });

  it("Cineon: middle grey near code 470, black at 95, and back", () => {
    expect(G.linToCineon(0.18) * 1023).toBeCloseTo(470, -1);
    expect(G.linToCineon(0) * 1023).toBeCloseTo(95, 3);
    expect(G.cineonToLin(G.linToCineon(0.42))).toBeCloseTo(0.42, 6);
  });
  it("an identity LUT given back to the app's Rec.709: the same picture as no LUT, whatever its input", () => {
    expect(worst(G.buildGradeLut({ ...base, lut: lut("dwg") }, id, N))).toBeLessThan(0.01);
    expect(worst(G.buildGradeLut({ ...base, lut: lut("cineon709") }, id, N))).toBeLessThan(0.01);
    expect(worst(G.buildGradeLut({ ...base, lut: lut("camera") }, id, N))).toBeLessThan(0.01);
    // A gamma 2.4 LUT gives the final picture: with the highlights eased it is the app's own conversion.
    expect(worst(G.buildGradeLut({ ...base, lut: { ...lut("gamma709"), output: "display", tonemap: true } }, id, N))).toBeLessThan(0.01);
  });
  it("the highlights eased (Cineon): bright light comes down, the mids stay", () => {
    const hot = { ...G.NEUTRAL_GRADE, exposure: 2.5 };
    const off = G.buildGradeLut({ ...hot, lut: lut("cineon709") }, id, N), on = G.buildGradeLut({ ...hot, lut: lut("cineon709", { tonemap: true }) }, id, N);
    const at = (l: Float32Array, i: number) => l[((i * N + i) * N + i) * 3];
    expect(at(on, 3)).toBeCloseTo(at(off, 3), 3);
    expect(at(on, N - 2)).toBeLessThanOrEqual(at(off, N - 2));
  });
  it("older LUTs: a camera kind is the camera log in, the others DWG / Intermediate", () => {
    expect(G.lutInputOf({ kind: "camera" })).toBe("camera");
    expect(G.lutInputOf({})).toBe("dwg");
    expect(G.lutInputOf({ input: "cineon709", kind: "camera" })).toBe("cineon709");
  });
});

